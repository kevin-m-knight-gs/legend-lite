"""THE one reader of a column's type in Python, as ``engine-client/src/types.ts`` is DataCube's (docs/
PYTHON_ASKS_DATACUBE_2026_10_15.md, item 4). A column's type is the compiler's: legend-lite's plain name (``Integer``),
or legend-engine's precise primitive by path (``meta::pure::precisePrimitives::BigInt``, a server's plan). What Python
needs from it -- its plain primitive -- is legend-lite's own lattice, generated by running it (``_type_facts.py``, the
table DataCube reads). Nothing here names a type to decide what it is: a name the table does not know is an ERROR, never
a guess, because a column read as the wrong type converts and shows wrongly without a word. On Python's standard library
alone (the compiler-only install)."""

from __future__ import annotations

from ._type_facts import TYPE_FACTS


class UnknownType(ValueError):
    """A type name legend-lite's lattice does not know: a column typed so is refused, never read as a guess."""


def plain_type(name: str) -> str:
    """The plain Pure primitive a reported type is (``meta::pure::precisePrimitives::Int`` is ``Integer``); an unknown
    name is refused (types.ts ``plainType``)."""
    fact = TYPE_FACTS.get(name)
    if fact is None:
        raise UnknownType(f"the compiler typed a column '{name}', which legend-lite does not read")
    return fact[0]
